export type Enums = typeof CATALOG.enums;
export type EventName = keyof typeof CATALOG.events;
export type TourId = Enums['tour'][number];
export type RouteName = Enums['route'][number];
export type Platform = Enums['platform'][number];
export type AccountMode = Enums['account_mode'][number];
export type Viewport = Enums['viewport'][number];

type Spec =
	{ enum: string } | { step_of: string } | { int: readonly [number, number] };

type PropValue<S> = S extends { enum: infer E extends keyof Enums }
	? Enums[E][number]
	: S extends { step_of: string }
		? string
		: S extends { int: readonly [number, number] }
			? number
			: never;

export type EventProps = {
	[N in EventName]: {
		-readonly [K in keyof (typeof CATALOG.events)[N]]: PropValue<
			(typeof CATALOG.events)[N][K]
		>;
	};
};

export type TrackArgs<N extends EventName> = keyof EventProps[N] extends never
	? [props?: undefined]
	: [props: EventProps[N]];

const matches = (
	spec: Spec,
	value: unknown,
	props: Record<string, unknown>,
): boolean => {
	if ('enum' in spec) {
		const allowed = (CATALOG.enums as Record<string, readonly string[]>)[
			spec.enum
		];
		return typeof value === 'string' && !!allowed?.includes(value);
	}
	if ('step_of' in spec) {
		const steps = (CATALOG.steps as Record<string, readonly string[]>)[
			String(props[spec.step_of])
		];
		return typeof value === 'string' && !!steps?.includes(value);
	}
	return (
		typeof value === 'number' &&
		Number.isInteger(value) &&
		value >= spec.int[0] &&
		value <= spec.int[1]
	);
};

export const isKnownEvent = (name: unknown): name is EventName =>
	typeof name === 'string' &&
	Object.prototype.hasOwnProperty.call(CATALOG.events, name);

export const validProps = (
	name: EventName,
	props: Record<string, unknown> = {},
): boolean => {
	const specs = CATALOG.events[name] as Record<string, Spec>;
	const keys = Object.keys(props);
	if (keys.length !== Object.keys(specs).length) return false;
	return keys.every(
		(key) => key in specs && matches(specs[key], props[key], props),
	);
};

export const isCatalogRoute = (name: unknown): name is RouteName =>
	typeof name === 'string' &&
	(CATALOG.enums.route as readonly string[]).includes(name);

export const copyProps = (
	name: EventName,
	props: Record<string, unknown> = {},
): Record<string, string | number> | null => {
	try {
		const specs = CATALOG.events[name];
		const keys = Object.keys(props);
		if (
			keys.length !== Object.keys(specs).length ||
			keys.some((key) => !Object.prototype.hasOwnProperty.call(specs, key))
		)
			return null;
		const snapshot: Record<string, unknown> = {};
		for (const key of keys) snapshot[key] = props[key];
		return validProps(name, snapshot)
			? (snapshot as Record<string, string | number>)
			: null;
	} catch {
		return null;
	}
};
