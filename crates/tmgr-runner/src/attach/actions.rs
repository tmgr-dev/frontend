#[derive(Clone, Copy, Debug)]
pub struct ActionDef {
    pub cmd: Cmd,
    pub keys: &'static [u8],
    pub hotkey: &'static str,
    pub label: &'static str,
    pub palette: bool,
}

const fn def(
    cmd: Cmd,
    keys: &'static [u8],
    hotkey: &'static str,
    label: &'static str,
    palette: bool,
) -> ActionDef {
    ActionDef {
        cmd,
        keys,
        hotkey,
        label,
        palette,
    }
}

