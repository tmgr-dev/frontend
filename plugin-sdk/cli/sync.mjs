#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const templateDir = join(here, '..', 'template');
const libDir = join(here, 'lib');

const notice = (from) =>
  `// Generated by plugin-sdk/cli/sync.mjs from plugin-sdk/template/${from}.\n// Generated, do not edit by hand: run \`node plugin-sdk/cli/sync.mjs\` from the app repo.\n`;

const withNotice = (from, source) => {
  if (!source.startsWith('#!')) return notice(from) + source;
  const end = source.indexOf('\n') + 1;
  return source.slice(0, end) + notice(from) + source.slice(end);
};

const read = (name) => readFileSync(join(templateDir, name), 'utf8');

const validateSource = read('validate.mjs');
const manifestImport = "'./manifest.generated.js'";
if (!validateSource.includes(manifestImport)) {
  throw new Error('validate.mjs no longer imports ./manifest.generated.js');
}

const outputs = new Map([
  [
    join(libDir, 'validate.mjs'),
    withNotice(
      'validate.mjs',
      validateSource.replace(manifestImport, "'./manifest.generated.cjs'"),
    ),
  ],
  [join(libDir, 'build.mjs'), withNotice('build.mjs', read('build.mjs'))],
  [
    join(libDir, 'manifest.generated.cjs'),
    withNotice('manifest.generated.js', read('manifest.generated.js')),
  ],
]);

const check = process.argv.includes('--check');
const stale = [];
for (const [path, content] of outputs) {
  if (check) {
    let current = null;
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      current = null;
    }
    if (current !== content) stale.push(path);
  } else {
    writeFileSync(path, content);
  }
}

if (check) {
  if (stale.length) {
    console.error(
      'Stale files, run `node plugin-sdk/cli/sync.mjs` from the app repo:',
    );
    stale.forEach((path) => console.error(` - ${path}`));
    process.exit(1);
  }
  console.log('plugin-sdk/cli/lib is up to date.');
} else {
  console.log(`Synced ${outputs.size} files.`);
}
